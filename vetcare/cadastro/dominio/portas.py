"""Portas de saída do módulo Cadastro."""
from __future__ import annotations

from typing import Protocol

from vetcare.compartilhado.tipos import Pagina, Paginacao

from .entidades import Animal, Tutor, Veterinario


class RepositorioDeTutores(Protocol):
    def salvar(self, tutor: Tutor) -> Tutor: ...
    def obter(self, id: int) -> Tutor | None: ...
    def obter_por_cpf(self, cpf: str) -> Tutor | None: ...
    def listar(self, paginacao: Paginacao, busca: str | None) -> Pagina[Tutor]: ...
    def excluir(self, id: int) -> None:
        """Levanta Conflito se houver registros dependentes (animais)."""
        ...


class RepositorioDeAnimais(Protocol):
    def salvar(self, animal: Animal) -> Animal: ...
    def obter(self, id: int) -> Animal | None: ...
    def listar(
        self, paginacao: Paginacao, busca: str | None, tutor_id: int | None
    ) -> Pagina[Animal]: ...
    def excluir(self, id: int) -> None:
        """Levanta Conflito se houver registros dependentes (consultas)."""
        ...


class RepositorioDeVeterinarios(Protocol):
    def salvar(self, vet: Veterinario) -> Veterinario: ...
    def obter(self, id: int) -> Veterinario | None: ...
    def obter_por_crmv(self, crmv: str) -> Veterinario | None: ...
    def listar(
        self, paginacao: Paginacao, busca: str | None, somente_ativos: bool
    ) -> Pagina[Veterinario]: ...
    def excluir(self, id: int) -> None: ...
